"""Compare global and block-local normalization for gerbil v3 synapse prediction.

Only the blocks listed in ``normalization_blocks.json`` are predicted. For every block,
the same v3 model and inference geometry are used twice:

1. global normalization, matching the production pipeline (mean/std over the full
   dilated IHC mask), and
2. block-local normalization (mean/std over the dilated IHC mask in the padded inference
   block, including its halo).

Local maxima are found once at the lowest requested threshold and then filtered at all
thresholds. This is mathematically equivalent to re-running local-maxima detection at
each higher absolute threshold and avoids unnecessary repeated work.
"""

