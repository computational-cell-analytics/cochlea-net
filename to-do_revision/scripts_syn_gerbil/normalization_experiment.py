def _open_raw(config):
    return read_image_data(
        config["raw_path"], config["raw_key"], from_s3=config.get("from_s3", False)
    )


def _open_low_mask(config):
    low_mask = read_image_data(config["low_mask_path"], config["low_mask_key"])
    if config.get("dilate_low_mask", False):
        print("Building the finalized G301L 9x9x9 dilated IHC mask", flush=True)
        low_mask = binary_dilation(
            np.asarray(low_mask), structure=np.ones((9, 9, 9), dtype=bool)
        ).astype("uint8")
    else:
        # The low-resolution arrays are only 30-45 M voxels. Keeping their binary form in
        # RAM avoids repeatedly decompressing the same chunks during the full-resolution
        # ResizedVolume scan used for production-equivalent global statistics.
        low_mask = (np.asarray(low_mask) != 0).astype("uint8")
    return low_mask


def _masked_stats(raw_values, mask_values):
    values = np.asarray(raw_values)[np.asarray(mask_values, dtype=bool)]
    if values.size == 0:
        raise RuntimeError("Selected inference block contains no voxels in the IHC mask.")
    return float(values.mean(dtype=np.float64)), float(values.std(dtype=np.float64)), int(values.size)


def _global_stats(raw, full_mask, config, output_folder, threads):
    stats_path = os.path.join(output_folder, "global_stats.json")
    if os.path.exists(stats_path):
        with open(stats_path) as f:
            result = json.load(f)
        print(f"Reusing cached global statistics: {result}", flush=True)
        return float(result["mean"]), float(result["std"])

    source = config.get("production_stats")
    if source is not None and os.path.exists(source):
        with open(source) as f:
            production = json.load(f)
        mean, std = float(production["mean"]), float(production["std"])
        provenance = source
    else:
        chunks = tuple(int(value) for value in getattr(raw, "chunks", (64, 64, 64)))
        block_shape = tuple(2 * value for value in chunks)
        print(
            f"Computing production-equivalent global mean/std with blocks {block_shape}",
            flush=True,
        )
        mean, std = mean_and_std(
            raw, block_shape=block_shape, n_threads=threads, mask=full_mask, verbose=True
        )
        mean, std = float(mean), float(std)
        provenance = "computed from the full raw volume under the resized dilated IHC mask"

    result = {"mean": mean, "std": std, "provenance": provenance}
    with open(stats_path, "w") as f:
        json.dump(result, f, indent=2)
        f.write("\n")
    return mean, std


def _load_model(device="cuda"):
    # Older full-module checkpoints refer to the training dataset by its historical
    # top-level module name. Register the package location before unpickling, matching
    # the production model-inspection path.
    try:
        import sys
        import flamingo_tools.synapse_detection.detection_dataset as detection_dataset
        sys.modules.setdefault("detection_dataset", detection_dataset)
    except ImportError:
        pass
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        obj = torch.load(MODEL, map_location="cpu", weights_only=False)
    model = _model_from_checkpoint(obj) if isinstance(obj, dict) and "model_state" in obj else obj
    return model.to(device).eval()


def _create_prediction(path, shape, chunks):
    group = zarr.open_group(path, mode="w")
    return group.create_array(
        "prediction",
        shape=shape,
        chunks=chunks,
        dtype="float32",
        fill_value=0,
        compressors=zarr.codecs.ZstdCodec(level=3),
    )


def _predict(model, raw_patch, mean, std):
    normalized = np.asarray(raw_patch, dtype="float32").copy()
    normalized -= float(mean)
    normalized /= float(std)
    tensor = torch.from_numpy(normalized[None, None]).to("cuda")
    with torch.no_grad():
        prediction = model(tensor)
    if isinstance(prediction, (tuple, list)):
        prediction = prediction[0]
    prediction = prediction.detach().cpu().numpy().squeeze(0)
    if prediction.ndim == 4 and prediction.shape[0] == 1:
        prediction = prediction[0]
    if prediction.ndim != 3:
        raise RuntimeError(f"Expected one v3 output channel, got shape {prediction.shape}.")
    return prediction.astype("float32", copy=False)


def _inner_slices(halo, block_shape):
    return tuple(slice(ha, ha + size) for ha, size in zip(halo, block_shape))


def _evaluate_block(
    prediction,
    segmentation,
    block,
    block_record,
    mode,
    thresholds,
):
    bb = tuple(slice(int(beg), int(end)) for beg, end in zip(block.begin, block.end))
    pred = np.asarray(prediction[bb])

    coords = find_local_maxima(
        pred,
        block_shape=pred.shape,
        min_distance=2,
        threshold_abs=min(thresholds),
        n_threads=1,
        verbose=False,
    )
    if len(coords):
        keep = np.ones(len(coords), dtype=bool)
        for axis, size in enumerate(pred.shape):
            keep &= coords[:, axis] >= PEAK_BORDER
            keep &= coords[:, axis] < size - PEAK_BORDER
        coords = coords[keep]

    # Add enough context for an exact <=3 um distance measurement around retained peaks.
    distance_halo = tuple(2 + int(np.ceil(DISTANCE_CUTOFF / vs)) for vs in VOXEL_SIZE)
    seg_patch, _ = _load_block(
        segmentation, block.begin, block.shape, distance_halo, padding_mode="constant"
    )
    distance, nearest = distance_transform_edt(
        np.asarray(seg_patch) == 0,
        sampling=VOXEL_SIZE,
        return_indices=True,
    )
    inner = _inner_slices(distance_halo, block.shape)
    distance = distance[inner]
    nearest_labels = np.asarray(seg_patch)[tuple(nearest)][inner]

    detections = []
    if len(coords):
        scores = pred[tuple(coords.T)]
        distances = distance[tuple(coords.T)]
        labels = nearest_labels[tuple(coords.T)]
        globals_ = coords + np.asarray(block.begin)[None]
        for coord, global_coord, score, dist, label in zip(
            coords, globals_, scores, distances, labels
        ):
            detections.append(
                {
                    "block_id": int(block_record["block_id"]),
                    "regime": block_record["regime"],
                    "target_label": int(block_record["target_label"]),
                    "normalization": mode,
                    "z": int(global_coord[0]),
                    "y": int(global_coord[1]),
                    "x": int(global_coord[2]),
                    "prediction_score": float(score),
                    "distance_to_ihc": float(dist),
                    "matched_ihc": int(label),
                }
            )

    rows = []
    det_table = pd.DataFrame(detections)
    for threshold in thresholds:
        if len(det_table):
            selected = det_table[det_table["prediction_score"] >= threshold]
            near = selected[selected["distance_to_ihc"] <= DISTANCE_CUTOFF]
            target = near[near["matched_ihc"] == int(block_record["target_label"])]
        else:
            selected = near = target = det_table
        rows.append(
            {
                "block_id": int(block_record["block_id"]),
                "regime": block_record["regime"],
                "target_label": int(block_record["target_label"]),
                "normalization": mode,
                "threshold": float(threshold),
                "n_all": int(len(selected)),
                "n_within_3um": int(len(near)),
                "n_target_ihc": int(len(target)),
                "prediction_mean_in_mask": float(pred[pred > 0].mean()) if np.any(pred > 0) else 0.0,
                "prediction_max": float(pred.max()),
            }
        )
    return rows, detections


def _validate_manifest(cochlea, manifest, raw, segmentation, full_mask):
    info = manifest["selection"][cochlea]
    expected_shape = tuple(info["shape"])
    if tuple(raw.shape) != expected_shape:
        raise RuntimeError(f"{cochlea}: raw shape {raw.shape} != manifest {expected_shape}")
    if tuple(segmentation.shape) != expected_shape:
        raise RuntimeError(
            f"{cochlea}: segmentation shape {segmentation.shape} != manifest {expected_shape}"
        )
    if tuple(full_mask.shape) != expected_shape:
        raise RuntimeError(f"{cochlea}: resized mask shape {full_mask.shape} != {expected_shape}")
    block_ids = [int(record["block_id"]) for record in info["blocks"]]
    if len(block_ids) != 8 or len(set(block_ids)) != 8:
        raise RuntimeError(f"{cochlea}: expected eight unique selected blocks, got {block_ids}")


def run_cochlea(cochlea, manifest, output_root, thresholds, threads, validate_only):
    started = time.perf_counter()
    config = CONFIG[cochlea]
    output_folder = os.path.join(output_root, cochlea)
    os.makedirs(output_folder, exist_ok=True)
    complete_path = os.path.join(output_folder, "complete.json")
    if os.path.exists(complete_path) and not validate_only:
        print(f"{cochlea}: complete marker exists, skipping", flush=True)
        return

    print(f"\nOpening {cochlea}", flush=True)
    raw = _open_raw(config)
    low_mask = _open_low_mask(config)
    full_mask = ResizedVolume(low_mask, raw.shape, order=0)
    segmentation = read_image_data(config["seg_path"], config["seg_key"])
    _validate_manifest(cochlea, manifest, raw, segmentation, full_mask)

    if validate_only:
        print(
            f"{cochlea}: validation OK; shape={raw.shape}, low mask={low_mask.shape}, "
            f"blocks={len(manifest['selection'][cochlea]['blocks'])}",
            flush=True,
        )
        return
    if not torch.cuda.is_available():
        raise RuntimeError("A CUDA GPU is required for prediction.")

    global_mean, global_std = _global_stats(raw, full_mask, config, output_folder, threads)
    if global_std <= 0:
        raise RuntimeError(f"Invalid global standard deviation: {global_std}")

    block_shape = tuple(manifest["block_shape"])
    halo = tuple(manifest["halo"])
    blocking = bic.utils.Blocking([0, 0, 0], list(raw.shape), list(block_shape))
    outputs = {
        mode: _create_prediction(
            os.path.join(output_folder, f"predictions_{mode}.zarr"), raw.shape, block_shape
        )
        for mode in ("global", "local")
    }
    model = _load_model()
    local_stats = []

    for index, record in enumerate(manifest["selection"][cochlea]["blocks"], start=1):
        block = blocking.get_block(int(record["block_id"]))
        raw_patch, _ = _load_block(raw, block.begin, block_shape, halo, padding_mode="reflect")
        mask_patch, _ = _load_block(
            full_mask, block.begin, block_shape, halo, padding_mode="constant"
        )
        local_mean, local_std, n_masked = _masked_stats(raw_patch, mask_patch)
        if local_std <= 0:
            raise RuntimeError(f"{cochlea} block {record['block_id']}: local std is {local_std}")
        local_stats.append(
            {
                "block_id": int(record["block_id"]),
                "regime": record["regime"],
                "target_label": int(record["target_label"]),
                "global_mean": global_mean,
                "global_std": global_std,
                "local_mean": local_mean,
                "local_std": local_std,
                "n_masked_voxels_in_padded_block": n_masked,
            }
        )
        print(
            f"{cochlea}: block {index}/8 id={record['block_id']} {record['regime']}; "
            f"local mean/std={local_mean:.3f}/{local_std:.3f}",
            flush=True,
        )

        inner = _inner_slices(halo, block.shape)
        inner_mask = np.asarray(mask_patch[inner], dtype=bool)
        bb = tuple(slice(int(beg), int(end)) for beg, end in zip(block.begin, block.end))
        for mode, (mean, std) in {
            "global": (global_mean, global_std),
            "local": (local_mean, local_std),
        }.items():
            pred = _predict(model, raw_patch, mean, std)[inner]
            pred[~inner_mask] = 0
            outputs[mode][bb] = pred

    pd.DataFrame(local_stats).to_csv(
        os.path.join(output_folder, "normalization_stats.tsv"), sep="\t", index=False
    )

    summary_rows, detection_rows = [], []
    for record in manifest["selection"][cochlea]["blocks"]:
        block = blocking.get_block(int(record["block_id"]))
        for mode, prediction in outputs.items():
            summary, detections = _evaluate_block(
                prediction, segmentation, block, record, mode, thresholds
            )
            summary_rows.extend(summary)
            detection_rows.extend(detections)

    summary_table = pd.DataFrame(summary_rows)
    summary_table.insert(0, "cochlea", cochlea)
    summary_table.to_csv(
        os.path.join(output_folder, "threshold_counts.tsv"), sep="\t", index=False
    )
    detections_table = pd.DataFrame(detection_rows)
    if len(detections_table):
        detections_table.insert(0, "cochlea", cochlea)
    detections_table.to_csv(
        os.path.join(output_folder, "detections_threshold_0.3.tsv"), sep="\t", index=False
    )

    elapsed = time.perf_counter() - started
    completion = {
        "cochlea": cochlea,
        "elapsed_seconds": elapsed,
        "model": MODEL,
        "thresholds": list(thresholds),
        "distance_cutoff_um": DISTANCE_CUTOFF,
        "excluded_block_border_voxels": PEAK_BORDER,
        "n_blocks": len(manifest["selection"][cochlea]["blocks"]),
    }
    with open(complete_path, "w") as f:
        json.dump(completion, f, indent=2)
        f.write("\n")
    print(f"{cochlea}: complete in {elapsed / 60:.1f} minutes", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--output-root", required=True)
    parser.add_argument("--cochleae", nargs="+", required=True, choices=sorted(CONFIG))
    parser.add_argument("--thresholds", nargs="+", type=float, default=list(THRESHOLDS))
    parser.add_argument("--threads", type=int, default=8)
    parser.add_argument("--validate-only", action="store_true")
    args = parser.parse_args()

    with open(args.manifest) as f:
        manifest = json.load(f)
    thresholds = tuple(sorted(set(args.thresholds)))
    if not thresholds or min(thresholds) < 0 or max(thresholds) > 1:
        raise ValueError(f"Invalid thresholds: {thresholds}")
    missing = set(args.cochleae) - set(manifest.get("selection", {}))
    if missing:
        raise ValueError(f"Cochleae missing from manifest: {sorted(missing)}")

    for cochlea in args.cochleae:
        run_cochlea(
            cochlea, manifest, args.output_root, thresholds, args.threads, args.validate_only
        )


if __name__ == "__main__":
    main()
